import type { Question } from "./types";

type Five = [string, string, string, string, string];
type Four = [string, string, string, string];

function q(
  id: string,
  topicId: string,
  guide: string,
  statement: string,
  stem: string,
  choices: Five,
  answer: 0 | 1 | 2 | 3 | 4,
  why: string,
  wrong: Four,
): Question {
  const aligned = ["", "", "", "", ""];
  let n = 0;
  for (let i = 0; i < 5; i++) {
    if (i === answer) continue;
    aligned[i] = wrong[n++] ?? "";
  }
  return {
    id,
    topicId,
    guide,
    statement,
    stem: [stem],
    choices: [...choices],
    answer,
    explanation: why,
    wrong: aligned,
    objective: statement,
  };
}

